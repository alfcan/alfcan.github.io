#!/usr/bin/env python3
"""Generate an academic CV in LaTeX (cv/cv.tex) from the website data in data/*.json.

Usage:
    python scripts/build_cv.py [output.tex]

Sections that the website does not cover (education, awards, service, ...) can be
added through the optional file data/cv-extra.json:

    [
      {
        "title": "Education",
        "items": [
          {"period": "2024 -- present", "title": "PhD in Computer Science", "details": "University of Salerno"}
        ]
      }
    ]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
DEFAULT_OUTPUT = ROOT / "cv" / "cv.tex"

PUBLICATION_GROUPS = [
    ("journal", "Journal Articles", "J"),
    ("conference", "Conference Papers", "C"),
    ("book", "Book Chapters", "B"),
    ("other", "Preprints and Other", "P"),
]
TEACHING_TYPES = {
    "lab": "Lab",
    "exercise": "Exercise session",
    "course": "Course",
    "lecture": "Lecture",
    "seminar": "Seminar",
    "workshop": "Workshop",
    "tutoring": "Tutoring",
}
DEGREES = {"bachelor": "Bachelor's thesis", "master": "Master's thesis", "phd": "PhD thesis"}

NEWLINE = r" \newline "

LATEX_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}

PREAMBLE = r"""% Generated by scripts/build_cv.py from data/*.json. Do not edit by hand:
% change the website data (or data/cv-extra.json) and run the script again.
\documentclass[11pt,a4paper]{article}
\usepackage{iftex}
\ifPDFTeX
  \usepackage[T1]{fontenc}
  \usepackage[utf8]{inputenc}
  \usepackage{lmodern}
\else
  \usepackage{fontspec}
\fi
\usepackage[a4paper,margin=2cm]{geometry}
\usepackage{xcolor}
\usepackage{enumitem}
\usepackage{titlesec}
\usepackage[hidelinks]{hyperref}

\definecolor{accent}{HTML}{1D4ED8}
\pagestyle{plain}
\setlength{\parindent}{0pt}
\setlist{nosep, leftmargin=*}
\titleformat{\section}{\large\bfseries\color{accent}}{}{0pt}{}[\vspace{-6pt}\rule{\textwidth}{0.4pt}]
\titlespacing*{\section}{0pt}{14pt}{6pt}
\titleformat{\subsection}{\normalsize\bfseries}{}{0pt}{}
\titlespacing*{\subsection}{0pt}{8pt}{3pt}

% \cvitem{left label}{body}
\newcommand{\cvitem}[2]{%
  \begin{tabular*}{\textwidth}{@{}p{0.15\textwidth}@{\hspace{0.02\textwidth}}p{0.83\textwidth}@{}}
    \raggedright #1 & \raggedright\arraybackslash #2
  \end{tabular*}\par\vspace{5pt}}
\newcommand{\link}[2]{\href{#1}{\color{accent}#2}}
"""


def tex(text) -> str:
    """Escape plain text for LaTeX."""
    return "".join(LATEX_ESCAPES.get(ch, ch) for ch in str(text or "")).strip()


def url(value: str) -> str:
    """Escape a URL for use inside \\href."""
    return str(value or "").replace("\\", "").replace("%", r"\%").replace("#", r"\#").replace("{", "").replace("}", "")


def load(name: str, default=None):
    path = DATA / name
    if not path.exists():
        if default is None:
            raise SystemExit(f"Missing {path}")
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def header(profile: dict) -> list:
    contacts = []
    if profile.get("email"):
        contacts.append(rf"\link{{mailto:{url(profile['email'])}}}{{{tex(profile['email'])}}}")
    if profile.get("website"):
        shown = profile["website"].split("://", 1)[-1].rstrip("/")
        contacts.append(rf"\link{{{url(profile['website'])}}}{{{tex(shown)}}}")
    links = [
        rf"\link{{{url(link['url'])}}}{{{tex(link['label'])}}}"
        for link in profile.get("links", [])
        if link.get("url")
    ]
    subtitle = ", ".join(tex(v) for v in (profile.get("tagline"), profile.get("affiliation")) if v)
    lines = [r"\begin{center}", rf"  {{\Huge\bfseries {tex(profile['name'])}}}\\[6pt]"]
    if subtitle:
        lines.append(rf"  {{\large {subtitle}}}\\[4pt]")
    for row in (contacts, links):
        if row:
            lines.append("  " + r" \,\textperiodcentered\, ".join(row) + r"\\[2pt]")
    lines.append(r"\end{center}")
    return lines


def position(profile: dict) -> list:
    body = [rf"\textbf{{{tex(profile.get('tagline'))}}}"]
    if profile.get("affiliation"):
        body[0] += f", {tex(profile['affiliation'])}"
    if profile.get("researchTrack"):
        body.append(tex(profile["researchTrack"]))
    supervisors = [s for s in profile.get("supervisors", []) if s.get("name")]
    if supervisors:
        names = ", ".join(
            rf"\link{{{url(s['url'])}}}{{{tex(s['name'])}}}" if s.get("url") else tex(s["name"])
            for s in supervisors
        )
        body.append(f"Supervisors: {names}")
    return [r"\section{Current Position}", rf"\cvitem{{Present}}{{{NEWLINE.join(body)}}}"]


def extra_sections(extra: list) -> list:
    lines = []
    for section in extra:
        items = section.get("items") or []
        if not items:
            continue
        lines.append(rf"\section{{{tex(section.get('title'))}}}")
        for item in items:
            body = rf"\textbf{{{tex(item.get('title'))}}}"
            if item.get("details"):
                body += rf" \newline {tex(item['details'])}"
            lines.append(rf"\cvitem{{{tex(item.get('period'))}}}{{{body}}}")
    return lines


def publications(works: list, owner: str) -> list:
    works = sorted(works, key=lambda w: w.get("year") or 0, reverse=True)
    lines = []
    for category, heading, prefix in PUBLICATION_GROUPS:
        group = [w for w in works if (w.get("category") or "other") == category]
        if not group:
            continue
        lines.append(rf"\subsection{{{heading}}}")
        lines.append(rf"\begin{{enumerate}}[label={{[{prefix}\arabic*]}}, itemsep=4pt]")
        for work in group:
            authors = tex(work.get("authors")).replace(tex(owner), rf"\textbf{{{tex(owner)}}}")
            parts = [authors, rf"\emph{{{tex(work.get('title'))}}}"]
            if work.get("venue"):
                parts.append(tex(work["venue"]))
            if work.get("year"):
                parts.append(str(work["year"]))
            entry = ". ".join(p.rstrip(".") for p in parts if p) + "."
            refs = []
            if work.get("doi"):
                refs.append(rf"DOI: \link{{https://doi.org/{url(work['doi'])}}}{{{tex(work['doi'])}}}")
            for artifact in work.get("artifacts") or []:
                refs.append(rf"\link{{{url(artifact['url'])}}}{{{tex(artifact['label'])}}}")
            if refs:
                entry += r" {\small " + r" \,\textperiodcentered\, ".join(refs) + "}"
            lines.append(rf"  \item {entry}")
        lines.append(r"\end{enumerate}")
    return [r"\section{Publications}", *lines] if lines else []


def teaching(entries: list) -> list:
    if not entries:
        return []
    lines = [r"\section{Teaching}"]
    for entry in sorted(entries, key=lambda e: e.get("academicYear") or "", reverse=True):
        title = rf"\textbf{{{tex(entry.get('title'))}}}"
        if entry.get("hours"):
            title += rf" ({entry['hours']}h)"
        course = tex(entry.get("course"))
        role = tex(entry.get("role")) or TEACHING_TYPES.get(entry.get("type"), "")
        first = f"{role}, course of {course}" if role and course else role or course
        where = ", ".join(tex(entry.get(k)) for k in ("program", "department", "institution") if entry.get(k))
        body = NEWLINE.join(part for part in (title, first, where) if part)
        lines.append(rf"\cvitem{{{tex(entry.get('academicYear'))}}}{{{body}}}")
    return lines


def supervision(students: list, owner: str) -> list:
    if not students:
        return []
    lines = [r"\section{Thesis Supervision}"]
    for student in sorted(students, key=lambda s: s.get("academicYear") or "", reverse=True):
        degree = DEGREES.get(student.get("degree"), tex(student.get("degree")))
        if student.get("status") == "ongoing":
            degree += ", ongoing"
        body = [rf"\textbf{{{tex(student.get('name'))}}}, {degree}"]
        if student.get("institution"):
            body[0] += f", {tex(student['institution'])}"
        if student.get("topic"):
            body.append(rf"\emph{{{tex(student['topic'])}}}")
        others = [
            tex(s["name"])
            for s in student.get("coSupervisors") or []
            if s.get("name") and owner.lower() not in s["name"].lower()
        ]
        if others:
            body.append(f"Co-supervised with {', '.join(others)}")
        lines.append(rf"\cvitem{{{tex(student.get('academicYear'))}}}{{{NEWLINE.join(body)}}}")
    return lines


def build() -> str:
    profile = load("profile.json")
    works = [w for w in load("publications.json", []) if w.get("category") != "artifact"]
    owner = profile["name"]

    body = [*header(profile)]
    if profile.get("bio"):
        body += [r"\section{Profile}", tex(profile["bio"])]
    body += position(profile)
    body += extra_sections(load("cv-extra.json", []))
    if profile.get("researchInterests"):
        body.append(r"\section{Research Interests}")
        body.append(r"\begin{itemize}")
        body += [rf"  \item {tex(interest)}" for interest in profile["researchInterests"]]
        body.append(r"\end{itemize}")
    body += publications(works, owner)
    body += teaching(load("teaching.json", []))
    body += supervision(load("students.json", []), owner)
    body += [r"\vfill", r"\begin{center}\footnotesize\color{gray} Last updated: \today\end{center}"]

    meta = rf"\hypersetup{{pdftitle={{{tex(owner)} -- Curriculum Vitae}}, pdfauthor={{{tex(owner)}}}}}"
    return "\n".join([PREAMBLE, meta, "", r"\begin{document}", *body, r"\end{document}", ""])


def main() -> None:
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUTPUT
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build(), encoding="utf-8")
    print(f"CV written to {output}")


if __name__ == "__main__":
    main()
